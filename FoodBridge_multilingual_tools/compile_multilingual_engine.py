# -*- coding: utf-8 -*-
"""
Master Multilingual Engine Compiler for FoodBridge.

Merges the base 10-language dictionaries, adds the supplied translation keys,
and writes the compiled dictionaries to app.js.

NOTE: The original code provided ended partway through the ph_hist_search
translations. Complete that mapping before running this compiler.
"""
import json
import re
from pathlib import Path

# Import base dictionaries
from make_all_languages import en_dict
from build_full_languages import es_dict
import dict_hi
import dict_ta
import dict_te_bn
import dict_fr_de
import dict_zh_ar

# Base 10 dictionaries
all_dicts = {
    "en": dict(en_dict),
    "es": dict(es_dict),
    "hi": dict(dict_hi.hi_dict),
    "ta": dict(dict_ta.ta_dict),
    "te": dict(dict_te_bn.te_dict),
    "bn": dict(dict_te_bn.bn_dict),
    "fr": dict(dict_fr_de.fr_dict),
    "de": dict(dict_fr_de.de_dict),
    "zh": dict(dict_zh_ar.zh_dict),
    "ar": dict(dict_zh_ar.ar_dict),
}

# New keys translations for all 10 languages
new_keys_map = {
    "btn_export_csv": {
        "en": "📥 Export CSV",
        "es": "📥 Exportar CSV",
        "hi": "📥 CSV निर्यात करें",
        "ta": "📥 CSV பதிவிறக்குக",
        "te": "📥 CSV ఎగుమతి చేయండి",
        "bn": "📥 CSV এক্সপোর্ট করুন",
        "fr": "📥 Exporter CSV",
        "de": "📥 CSV exportieren",
        "zh": "📥 导出 CSV",
        "ar": "📥 تصدير CSV",
    },
    "ph_hist_search": {
        "en": "Search orders, batches, donors or couriers...",
        "es": "Buscar pedidos, lotes, donantes o repartidores...",
        "hi": "ऑर्डर, बैच, दानदाताओं या डिलीवरी कर्मियों को खोजें...",
        "ta": "ஆர்டர்கள், தொகுதிகள், நன்கொடையாளர்கள் அல்லது டெலிவரி பணியாளர்களைத் தேடுங்கள்...",
        "te": "ఆర్డర్లు, బ్యాచ్‌లు, దాతలు లేదా డెలివరీ సిబ్బందిని శోధించండి...",
        "bn": "অর্ডার, ব্যাচ, দাতা বা ডেলিভারি কর্মীদের খুঁজুন...",
        "fr": "Rechercher des commandes, lots, donateurs ou livreurs...",
        "de": "Bestellungen, Chargen, Spender oder Kuriere suchen...",
        "zh": "搜索订单、批次、捐赠者或配送员...",
        "ar": "ابحث عن الطلبات أو الدفعات أو المتبرعين أو مندوبي التوصيل...",
    },
}

# Merge new translations into each language dictionary.
for key, translations in new_keys_map.items():
    for lang, dictionary in all_dicts.items():
        if lang in translations:
            dictionary[key] = translations[lang]
        else:
            print(f"WARNING: Translation missing for key={key!r}, language={lang!r}")

# Compile dictionaries into JavaScript.
# Output is valid JavaScript: const translations = {...};
output_path = Path("app.js")
serialized = json.dumps(all_dicts, ensure_ascii=False, indent=2)
output_path.write_text(
    "/* Generated by compile_multilingual_engine.py */\n"
    f"const translations = {serialized};\n",
    encoding="utf-8",
)

print(f"Compiled {len(all_dicts)} languages into {output_path.resolve()}")
for lang, dictionary in all_dicts.items():
    missing = [
        key for key in new_keys_map
        if key not in dictionary or not str(dictionary[key]).strip()
    ]
    print(f"{lang}: {len(dictionary)} total keys; missing/empty new keys: {len(missing)}")
    if missing:
        print("  " + ", ".join(missing))
